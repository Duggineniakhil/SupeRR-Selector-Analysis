"""T14 — Out-of-time validation (planning/08 §2.4).

Ratings are built ONLY from 2022–2024 matches (EB hyper-parameters, calibration, recency all
anchored at the end of 2024). They are then compared with what happened in 2025–2026.

Predictors (from 2022–24)            Targets (2025–26)
  M2  all-balls EB value (final)       primary:   pressure value per ball (context-adjusted)
  M1  pressure-only EB value           secondary: raw pressure SR (bat) / pressure economy (bowl)
  M3  hybrid (B + shrunk residual)
  raw pressure value (no shrinkage)
  naive: raw pressure SR / economy
  naive: overall SR / economy

Evaluation players: ≥ min pressure balls in 2025–26 and n_eff ≥ 30 in 2022–24.
Metrics: weighted Pearson (weights = test n_eff) and Spearman, with 90% player-bootstrap CIs;
"top-10 capture" = mean 2025–26 percentile of each predictor's top 10 (50 = no skill).
All results are CORRELATIONAL — they show how well past ratings tracked later performance,
not a guarantee of future performance.

Output: outputs/validation/out_of_time.md (no names)
"""
from __future__ import annotations

import numpy as np
import pandas as pd

import estimators as E
import player_metrics as pm
from common import load_config, md_table, path

TRAIN_END, TEST_START = 2024, 2025
MIN_TEST = {"bat": 60, "bowl": 75}


def wcorr(x, y, w):
    mx, my = np.average(x, weights=w), np.average(y, weights=w)
    return np.average((x - mx) * (y - my), weights=w) / np.sqrt(
        np.average((x - mx) ** 2, weights=w) * np.average((y - my) ** 2, weights=w))


def boot_ci(x, y, w, reps, rng):
    n = len(x)
    pe, sp = [], []
    for _ in range(reps):
        i = rng.integers(0, n, n)
        pe.append(wcorr(x[i], y[i], w[i]))
        sp.append(pd.Series(x[i]).corr(pd.Series(y[i]), method="spearman"))
    return np.nanpercentile(pe, [5, 95]), np.nanpercentile(sp, [5, 95])


def run(cfg: dict | None = None):
    cfg = cfg or load_config()
    interim, out = path(cfg, "interim"), path(cfg, "outputs")
    mc = cfg["metrics"]
    kappa, H = mc["tier_credibility_fallback"], mc["recency_half_life_years"]
    seed = cfg["pressure"]["seed"]
    rng = np.random.default_rng(seed)
    d = pd.read_parquet(interim / "rating_balls.parquet")
    d_tr, d_te = d[d.year <= TRAIN_END], d[d.year >= TEST_START]
    ref_tr = d_tr.match_date.max()

    L = ["# T14 — Out-of-time validation (train 2022–24 → test 2025–26)", "",
         "Generated by `src/validation_oot.py`. Every predictor is built from 2022–24 data only "
         f"(reference date {ref_tr.date()}). Results are **correlational**: they show how well ratings "
         "built from past data tracked later pressure performance. They do not guarantee future performance.", ""]
    for kind in ("bat", "bowl"):
        name = "Batting" if kind == "bat" else "Bowling"
        bv_tr = E.ball_values(d_tr, kind)
        bv_te = E.ball_values(d_te, kind)
        fit = E.train(bv_tr, kind, cfg, ref_tr, seed)
        f, st_tr = fit["feat"], fit["stats"]
        st_te = E.player_stats(bv_te, kappa, d_te.match_date.max(), H)
        tb_tr = (pm.batting if kind == "bat" else pm.bowling)(
            d_tr.assign(rec=pm.recency(d_tr.match_date, str(ref_tr.date()), H)), kappa, cfg)
        tb_te = (pm.batting if kind == "bat" else pm.bowling)(
            d_te.assign(rec=pm.recency(d_te.match_date, str(d_te.match_date.max().date()), H)), kappa, cfg)

        ids = st_te.index[st_te.n_P >= MIN_TEST[kind]].intersection(st_tr.index[st_tr.neff_A >= 30])
        y_val, w = st_te.loc[ids, "x_P"].to_numpy(), st_te.loc[ids, "neff_P"].to_numpy()
        if kind == "bat":
            y_raw, raw_lab = tb_te.sr_P.reindex(ids).to_numpy(), "pressure SR"
            naive = {"naive: raw pressure SR": tb_tr.sr_P, "naive: overall SR (non-pressure)": tb_tr.sr_N}
        else:
            y_raw, raw_lab = -tb_te.econ_P.reindex(ids).to_numpy(), "−pressure economy"
            naive = {"naive: raw pressure economy (−)": -tb_tr.econ_P, "naive: overall economy (−)": -tb_tr.econ_N}
        preds = {"M2 all-balls EB (final)": f.post_A, "M1 pressure-only EB": f.post_P,
                 "M3 hybrid (B + shrunk residual)": f.B + f.adv, "raw pressure value (no shrinkage)": st_tr.x_P,
                 **naive}
        rows = []
        for lab, p in preds.items():
            x = p.reindex(ids).to_numpy(dtype=float)
            ok = ~np.isnan(x) & ~np.isnan(y_val)
            ci_p, ci_s = boot_ci(x[ok], y_val[ok], w[ok], 1000, rng)
            ok2 = ok & ~np.isnan(y_raw)
            pct = pd.Series(y_val[ok]).rank(pct=True).to_numpy() * 100
            top = np.argsort(-x[ok])[:10]
            rows.append({"predictor (2022–24)": lab, "players": int(ok.sum()),
                         "r_w vs pressure value": wcorr(x[ok], y_val[ok], w[ok]),
                         "r 90% CI": f"[{ci_p[0]:.2f}, {ci_p[1]:.2f}]",
                         "Spearman": pd.Series(x[ok]).corr(pd.Series(y_val[ok]), method="spearman"),
                         "Spearman 90% CI": f"[{ci_s[0]:.2f}, {ci_s[1]:.2f}]",
                         f"Spearman vs {raw_lab}": pd.Series(x[ok2]).corr(pd.Series(y_raw[ok2]), method="spearman"),
                         "top-10 mean test percentile": pct[top].mean()})
        T = pd.DataFrame(rows)
        L += [f"## {name}", "",
              f"Evaluation players: ≥ {MIN_TEST[kind]} pressure balls in 2025–26 and n_eff ≥ 30 in 2022–24 "
              f"(n = {len(ids)}).", "", md_table(T, index=False, floatfmt="{:.3f}"), ""]
        best = T.iloc[T["r_w vs pressure value"].idxmax()]["predictor (2022–24)"]
        L += [f"- Highest weighted r vs later pressure value: **{best}**.",
              f"- Final estimator M2: r = {T.iloc[0]['r_w vs pressure value']:.3f} {T.iloc[0]['r 90% CI']}; "
              f"its 2022–24 top 10 averaged the {T.iloc[0]['top-10 mean test percentile']:.0f}th percentile "
              "of 2025–26 pressure value (50 = no skill).", ""]
    (out / "validation" / "out_of_time.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    return L


if __name__ == "__main__":
    run()
