"""T13 — Sensitivity & alternative-ranking scenarios (planning/08 §3, adapted to the final M2
estimator from decisions D5/D6).

Each scenario re-ranks the eligible pool after changing one assumption. Scenario ranks use the
EB posterior of the scenario's value (the final M2 calibration slopes are positive for both
lists, so posterior order = rating order).

Scenarios
  EST_M1 / EST_M3        alternative estimators (pressure-only; hybrid)
  PRESS_top15 / top35    pressure = top 15% / 35% of leverage (changes eligibility pool)
  PRESS_rulePI           pressure = top 25% of the rule-based Pressure Index (pool)
  COMP_ipl_only          only IPL evidence (κ: T2–T4 = 0)
  COMP_T1T2              IPL + top-10 T20I only (κ: T3/T4 = 0)
  COMP_no_discount       all tiers weight 1
  REC_H1 / REC_Hinf      recency half-life 1 year / no recency weighting
  SHR_none / SHR_weak    no shrinkage (raw value) / prior variance τ² × 2
  ELIG_x0.75 / x1.5      eligibility thresholds × 0.75 / × 1.5
  ELIG_no_activity       no "active since 2025" filter
  WPA_only               rank by pressure WPA per 100 balls (T9)
  LIW_all_balls          all balls, each weighted by its leverage (high-stakes balls count more)

Robustness label per main top-10 pick: Robust (top 10 in ≥ 80% of scenarios), Moderate (50–80%),
Fragile (< 50%). Pre-stated swap rule (planning/08 §3): a Fragile pick at main rank 8–10 is
swapped with a Robust player at rank 11–12 whose 90% bootstrap rank interval overlaps.

Outputs: outputs/validation/sensitivity.md (aggregates, no names),
         outputs/rankings/{batting,bowling}_robustness.csv (+ .md) [local only]
"""
from __future__ import annotations

import copy

import numpy as np
import pandas as pd
from scipy.stats import kendalltau

import estimators as E
from common import load_config, md_table, path


def pool_from(bv: pd.DataFrame, kind: str, P: np.ndarray, min_n: float, min_units: int,
              active: pd.Series | None) -> pd.Index:
    x = bv.assign(P=P)
    cnt = x[x.P & (x.legal if kind == "bowl" else True)].groupby("pid").size()
    units = x[x.P].groupby("pid").match_id.nunique()
    ok = (cnt >= min_n).reindex(units.index, fill_value=False) & (units >= min_units)
    ids = ok[ok].index
    if active is not None:
        ids = ids[active.reindex(ids).fillna(False).to_numpy()]
    return ids


def rank_in(score: pd.Series, pool: pd.Index) -> pd.Series:
    return score.reindex(pool).rank(ascending=False, method="min")


def run(cfg: dict | None = None):
    cfg = cfg or load_config()
    interim, out = path(cfg, "interim"), path(cfg, "outputs")
    d = pd.read_parquet(interim / "rating_balls.parquet")
    pr = pd.read_parquet(interim / "pressure.parquet")[["match_id", "innings", "innings_ball_num", "pi"]]
    d = d.merge(pr, on=["match_id", "innings", "innings_ball_num"], how="left")
    rel = pd.read_pickle(interim / "reliability.pkl")
    players = pd.read_parquet(interim / "players.parquet").set_index("player_id")
    active = players.active_since_cutoff
    seed = cfg["pressure"]["seed"]
    ref = pd.Timestamp(cfg["reference_date"])

    L = ["# T13 — Sensitivity & alternative-ranking scenarios", "",
         "Generated by `src/sensitivity.py`. Final estimator = M2 (all-balls, EB-shrunk; decisions D5/D6). "
         "Per-player robustness tables are local only (`outputs/rankings/`). This report has no names.", "",
         "**Design note:** M2 uses all balls *without* leverage weights, so the definition of pressure "
         "affects M2 only through the context baselines and the eligibility pool. Scenario LIW_all_balls "
         "tests a leverage-weighted variant (high-stakes balls count more).", ""]

    for kind in ("bat", "bowl"):
        name = "batting" if kind == "bat" else "bowling"
        bv = E.ball_values(d, kind)
        src = d[d.is_ball_faced] if kind == "bat" else d
        bv["legal"] = src.is_legal.to_numpy()
        bv["li"] = src.li.to_numpy()
        bv["pi"] = src.pi.to_numpy()
        bv["innings"] = src.innings.to_numpy()
        bv["is_ipl"] = src.is_ipl.to_numpy()
        el = rel[kind]
        min_n, min_u = el["min_pressure_n"], el["min_pressure_units"]
        base_P = bv.P.to_numpy()
        base_pool = pool_from(bv, kind, base_P, min_n, min_u, active)

        base_fit = E.train(bv, kind, cfg, ref, seed)
        base_score = base_fit["feat"].post_A
        base_rank = rank_in(base_score, base_pool)
        main = pd.read_csv(out / "rankings" / f"{name}_ratings.csv", index_col=0)
        assert set(main.index) == set(base_pool), "base pool differs from T11 pool"

        scen: dict[str, pd.Series] = {}
        # rank by EB evidence (calibration slopes can be negative for noisy estimators)
        scen["EST_M1"] = rank_in(base_fit["feat"].post_P, base_pool)
        scen["EST_M3"] = rank_in(base_fit["feat"].B + base_fit["feat"].adv, base_pool)

        # pressure-definition scenarios (pool changes; M2 score unchanged)
        ref_mask = ~np.isnan(bv.li.to_numpy())
        for lab, q in (("PRESS_top15", .85), ("PRESS_top35", .65)):
            thr = bv.groupby("is_ipl").li.transform(lambda s: s.quantile(q)).to_numpy()
            P = (bv.li.to_numpy() >= thr) & ref_mask
            scen[lab] = rank_in(base_score, pool_from(bv, kind, P, min_n, min_u, active))
        thr = bv.groupby("innings").pi.transform(lambda s: s.quantile(.75)).to_numpy()
        P = np.nan_to_num(bv.pi.to_numpy(), nan=-9) >= thr
        scen["PRESS_rulePI"] = rank_in(base_score, pool_from(bv, kind, P, min_n, min_u, active))

        # competition / recency scenarios (re-fit EB on modified weights)
        def refit(mod):
            c = copy.deepcopy(cfg); mod(c)
            return E.train(bv, kind, c, ref, seed)["feat"].post_A
        k = cfg["metrics"]["tier_credibility_fallback"]
        scen["COMP_ipl_only"] = rank_in(refit(lambda c: c["metrics"].update(
            tier_credibility_fallback={**k, "T2_T20I_TOP": 1e-9, "T3_T20I_OTHER": 1e-9, "T4_A_TEAM": 1e-9})), base_pool)
        scen["COMP_T1T2"] = rank_in(refit(lambda c: c["metrics"].update(
            tier_credibility_fallback={**k, "T3_T20I_OTHER": 1e-9, "T4_A_TEAM": 1e-9})), base_pool)
        scen["COMP_no_discount"] = rank_in(refit(lambda c: c["metrics"].update(
            tier_credibility_fallback={t: 1.0 for t in k})), base_pool)
        scen["REC_H1"] = rank_in(refit(lambda c: c["metrics"].update(recency_half_life_years=1.0)), base_pool)
        scen["REC_Hinf"] = rank_in(refit(lambda c: c["metrics"].update(recency_half_life_years=1e6)), base_pool)

        # shrinkage scenarios
        st, g, hyp = base_fit["stats"], base_fit["grp"], base_fit["hyp"]
        scen["SHR_none"] = rank_in(st.x_A, base_pool)
        weak = copy.deepcopy(hyp["A"]); weak["tau2"] *= 2
        scen["SHR_weak"] = rank_in(E.eb_apply(weak, st.x_A, st.neff_A, g, st.kbar_A)[0], base_pool)

        # eligibility scenarios
        scen["ELIG_x0.75"] = rank_in(base_score, pool_from(bv, kind, base_P, min_n * .75, int(min_u * .75), active))
        scen["ELIG_x1.5"] = rank_in(base_score, pool_from(bv, kind, base_P, min_n * 1.5, int(min_u * 1.5), active))
        scen["ELIG_no_activity"] = rank_in(base_score, pool_from(bv, kind, base_P, min_n, min_u, None))

        # outcome-metric scenario
        tbl = pd.read_parquet(interim / f"player_{kind}.parquet")
        scen["WPA_only"] = rank_in(tbl.wpa_per100_P, base_pool)

        # leverage-weighted all balls
        bl = bv.assign(P=True)
        stl = E.player_stats(bl, k, ref, cfg["metrics"]["recency_half_life_years"])
        gl = g.reindex(stl.index).fillna("_all")
        hl = E.eb_fit(stl.x_P, stl.neff_P, gl, base_fit["sig2"], cfg["estimators"]["min_eb_eff_n"])
        scen["LIW_all_balls"] = rank_in(E.eb_apply(hl, stl.x_P, stl.neff_P, gl, stl.kbar_P)[0], base_pool)

        # ------------------------------ summary per scenario
        top10 = set(base_rank.nsmallest(10).index)
        top20 = base_rank.nsmallest(20).index
        rows = []
        for s, r in scen.items():
            t10 = set(r.nsmallest(10).index)
            rr = r.reindex(top20).fillna(len(base_pool) + 1)
            rows.append({"scenario": s, "pool": int(r.notna().sum()), "top10_overlap": len(top10 & t10),
                         "kendall_tau_top20": kendalltau(base_rank.reindex(top20), rr).statistic,
                         "entered": len(t10 - top10), "left": len(top10 - t10)})
        S = pd.DataFrame(rows)

        # ------------------------------ robustness per player (main top 20)
        R = pd.DataFrame(scen).reindex(top20)
        in10 = (R <= 10)
        rob = pd.DataFrame({
            "display_name": main.display_name.reindex(top20),
            "main_rank": base_rank.reindex(top20),
            "share_scenarios_top10": in10.mean(axis=1),
            "worst_scenario_rank": R.max(axis=1),
            "rank_p05": main.rank_p05.reindex(top20), "rank_p95": main.rank_p95.reindex(top20),
            "p_top10": main.p_top10.reindex(top20),
            "pct_P_balls_ipl": tbl.pct_P_balls_ipl.reindex(top20),
            "pct_P_balls_T34": tbl.pct_P_balls_T34.reindex(top20),
            "rank_COMP_ipl_only": R["COMP_ipl_only"], "rank_COMP_T1T2": R["COMP_T1T2"],
        })
        rob["robustness"] = pd.cut(rob.share_scenarios_top10, [-.01, .5, .8, 1.01], right=False,
                                   labels=["Fragile", "Moderate", "Robust"]).astype(str)
        rob["flag_T34_over_40pct"] = rob.pct_P_balls_T34 > 40
        rob = rob.sort_values("main_rank")

        # pre-stated swap rule
        swaps = []
        final = list(rob.index[:10])
        for pid in rob.index[(rob.main_rank >= 8) & (rob.main_rank <= 10)]:
            if rob.loc[pid, "robustness"] != "Fragile":
                continue
            for cand in rob.index[(rob.main_rank >= 11) & (rob.main_rank <= 12)]:
                c = rob.loc[cand]
                overlap = not (c.rank_p05 > rob.loc[pid, "rank_p95"] or rob.loc[pid, "rank_p05"] > c.rank_p95)
                if c.robustness == "Robust" and overlap and cand not in final:
                    final[final.index(pid)] = cand
                    swaps.append((int(rob.loc[pid, "main_rank"]), int(c.main_rank)))
                    break
        rob["in_final_top10"] = rob.index.isin(final)
        rob.to_csv(out / "rankings" / f"{name}_robustness.csv")
        (out / "rankings" / f"{name}_robustness.md").write_text(md_table(rob, floatfmt="{:.2f}") + "\n", encoding="utf-8")

        t10r = rob[rob.main_rank <= 10]
        L += [f"## {name.capitalize()}", "", "### Scenario summary (vs main ranking)", "",
              md_table(S, index=False, floatfmt="{:.2f}"), "",
              f"- Mean top-10 overlap across {len(S)} scenarios: **{S.top10_overlap.mean():.1f} / 10**; "
              f"median Kendall τ (top 20): {S.kendall_tau_top20.median():.2f}.",
              f"- Main top 10 robustness labels: {t10r.robustness.value_counts().to_dict()}",
              f"- Top-10 picks with > 40% of pressure balls from T3/T4 opposition: {int(t10r.flag_T34_over_40pct.sum())}",
              f"- Top-10 picks with 0% IPL pressure balls: {int((t10r.pct_P_balls_ipl == 0).sum())}; "
              f"of these still top 10 in IPL+T20I-top (COMP_T1T2): "
              f"{int(((t10r.pct_P_balls_ipl == 0) & (t10r.rank_COMP_T1T2 <= 10)).sum())}",
              f"- Pre-stated swap rule applied: {swaps if swaps else 'no swaps triggered'}", ""]
    (out / "validation" / "sensitivity.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    return L


if __name__ == "__main__":
    run()
