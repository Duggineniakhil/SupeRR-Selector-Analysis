"""T8 — Context-expected baselines per delivery (planning/04 §2).

For every delivery in the rating set, estimate what an average player would produce in the
same context:
    ctx = innings × phase → + wickets-in-hand bin → + pressure tier → + pace/spin
          → + competition tier → + season
Each level is a cell mean shrunk toward its parent level with k pseudo-balls:
    m_level = (Σy + k · m_parent) / (n + k)
so sparse cells inherit the broader expectation (hierarchical smoothing).

Batting targets (unit = ball faced): runs off the bat, striker dismissal, dot, boundary.
Bowling targets (unit = delivery bowled): runs charged, bowler wicket, dot (legal), boundary,
extras (wide / no-ball).
Also attaches λ = run value of a wicket at the ball's state (T5 ERR model).

Output: data_interim/rating_balls.parquet, outputs/validation/baselines_checks.md
"""
from __future__ import annotations

import pickle

import numpy as np
import pandas as pd

import models_par  # noqa: F401  (unpickling)
from common import load_config, md_table, path

BAT_TARGETS = {"runs": "e_runs", "out_striker": "e_out", "is_bat_dot": "e_dot", "is_boundary": "e_bnd"}
BOWL_TARGETS = {"bowler_runs": "e_conc", "is_bowler_wicket": "e_wkt", "is_bowler_dot": "e_bdot",
                "is_boundary": "e_bbnd", "is_extra": "e_extra"}


def rating_set(cfg: dict) -> pd.DataFrame:
    interim = path(cfg, "interim")
    bs = pd.read_parquet(interim / "ball_state.parquet")
    pr = pd.read_parquet(interim / "pressure.parquet")
    env = pd.read_parquet(interim / "env_par.parquet")
    key = ["match_id", "innings", "innings_ball_num"]
    d = bs.merge(pr[key + ["wp_before", "wp_after", "wpa_bat", "li", "li_weight", "pressure_tier",
                           "is_pressure"] + [c for c in pr.columns if c[:1] == "S" and c[1:2].isdigit()]],
                 on=key, how="inner")
    d = d.merge(env[["tier", "year", "env_par"]], on=["tier", "year"], how="left")
    keep = (d.innings <= 2) & ~d.is_non_delivery & d.li.notna()
    if cfg["metrics"]["exclude_no_result"]:
        keep &= ~d.is_no_result
    d = d[keep].copy()
    d["wbin"] = pd.cut(d.wickets_in_hand, cfg["pressure"]["outcome_context_wih_bins"]).astype(str)
    d["out_striker"] = (d.is_batter_dismissal & (d.dismissed_player_id == d.striker_id)).astype(float)
    d["out_nonstriker"] = (d.is_batter_dismissal & (d.dismissed_player_id == d.non_striker_id)).astype(float)
    d["is_extra"] = (d.is_wide | d.is_noball).astype(float)
    for c in ["is_bat_dot", "is_boundary", "is_bowler_wicket", "is_bowler_dot"]:
        d[c] = d[c].astype(float)
    d["runs"] = d["runs"].astype(float)
    d["bowler_runs"] = d["bowler_runs"].astype(float)
    return d.reset_index(drop=True)


def hierarchical_expectation(d: pd.DataFrame, unit: pd.Series, y: str, levels: list[list[str]],
                             k: float) -> np.ndarray:
    """Shrunk cell mean of y (over rows where unit is True), evaluated for every row of d."""
    sub = d[unit]
    est = np.full(len(d), sub[y].mean())
    cols: list[str] = []
    for lvl in levels:
        cols = cols + lvl
        g = sub.groupby(cols, observed=True)[y].agg(["sum", "count"])
        idx = pd.MultiIndex.from_frame(d[cols]) if len(cols) > 1 else pd.Index(d[cols[0]])
        s = g["sum"].reindex(idx).to_numpy(dtype=float)
        n = g["count"].reindex(idx).to_numpy(dtype=float)
        s, n = np.nan_to_num(s), np.nan_to_num(n)
        est = (s + k * est) / (n + k)
    return est


def run(cfg: dict | None = None):
    cfg = cfg or load_config()
    interim, out = path(cfg, "interim"), path(cfg, "outputs")
    with open(interim / "models" / "err.pkl", "rb") as fh:
        err = pickle.load(fh)
    d = rating_set(cfg)
    lv, k = cfg["baselines"]["levels"], cfg["baselines"]["shrink_k"]

    faced = d.is_ball_faced.astype(bool)
    for y, e in BAT_TARGETS.items():
        d[e] = hierarchical_expectation(d, faced, y, lv, k)
    bowled = pd.Series(True, index=d.index)
    for y, e in BOWL_TARGETS.items():
        d[e] = hierarchical_expectation(d, bowled, y, lv, k)
    d["lam"] = err.wicket_value(d.balls_rem_before, d.wickets_in_hand, d.env_par)

    d.to_parquet(interim / "rating_balls.parquet", index=False)

    # ---- checks: residual sums near zero, by broad context (no player-level output)
    L = ["# T8 — Context baselines: checks", "",
         f"Generated by `src/baselines.py`. Rating set = {len(d):,} deliveries (innings 1–2, decided or tied "
         f"matches, reliable targets); balls faced {int(faced.sum()):,}. Hierarchy {lv}; shrinkage k = {k}.", ""]
    rows = []
    for (y, e), unit in [*((kv, faced) for kv in BAT_TARGETS.items()),
                         *((kv, bowled) for kv in BOWL_TARGETS.items())]:
        x = d[unit]
        res = x[y] - x[e]
        by = x.assign(r=res).groupby(["innings", "phase", "pressure_tier"]).r.agg(["mean", "size"])
        by = by.loc[by["size"] >= 100, "mean"]          # ignore near-empty cells (e.g. n = 1)
        rows.append({"target": y, "unit": "faced" if unit is faced else "delivery", "mean": x[y].mean(),
                     "mean_residual": res.mean(), "max_abs_cell_residual(inn×phase×tier, n≥100)": by.abs().max()})
    L += ["## Residual check (actual − expected)", "",
          "Overall mean residual should be ≈ 0; broad cells should be small relative to the mean.", "",
          md_table(pd.DataFrame(rows), index=False, floatfmt="{:.4f}"), ""]
    lam = d.groupby(["innings", "phase"]).lam.describe()[["mean", "25%", "50%", "75%"]]
    L += ["## Wicket run value λ at actual states (runs)", "", md_table(lam, floatfmt="{:.2f}"), ""]
    (out / "validation" / "baselines_checks.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    return d, L


if __name__ == "__main__":
    run()
